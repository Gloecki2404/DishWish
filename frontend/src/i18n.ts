/** Translate a key (German for `de*`, English otherwise) and fill `{vars}`. */
export function t(lang: string, key: Key, vars?: Record<string, string | number>): string {
  let text: string = lang.startsWith("de") ? de[key] : en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

/** Translate a backend/WebSocket error code. */
export function tError(lang: string, code: string): string {
  const key = `err_${code}` as Key;
  return key in en ? t(lang, key) : t(lang, "err_unknown");
}


/** Language of the Home Assistant frontend (user setting), for code that runs before `hass` exists. */
export function uiLanguage(): string {
  try {
    const stored = localStorage.getItem("selectedLanguage");
    if (stored) return String(JSON.parse(stored));
  } catch {
    /* fall through */
  }
  return document.documentElement.lang || navigator.language || "en";
}
